// Mask filenames follow `<src without extension>-mask-<tone>.png`.
export function motifMaskSrc(src: string, tone: Exclude<MotifRecolor, 'none'>): string {
  const lastDot = src.lastIndexOf('.');
  const base = lastDot === -1 ? src : src.slice(0, lastDot);
  return `${base}-mask-${tone}.png`;
}
